# 1. การต่อข้อความ (String Concatenation)
university = "KMUT" + "NB"  # ได้ผลลัพธ์เป็น "KMUTNB"
major = "Computer Engineering"
welcome_msg = "Welcome to " + major + ", " + university

# 2. การคำนวณตัวเลข (Calculation) เปรียบเทียบกับข้อความ
num_str = "1" + "2"  # ได้ "12"
num_val = 1 + 2      # ได้ 3

# แสดงผลลัพธ์
print(welcome_msg)
print("String Join ('1' + '2'):", num_str)
print("Numeric Sum  (1 + 2):", num_val)